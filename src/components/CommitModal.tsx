import { useEffect, useId, useRef, useState, type KeyboardEvent as ReactKeyboardEvent, type ReactElement } from "react";
import { openUrl } from "@tauri-apps/plugin-opener";
import { isTauri } from "@tauri-apps/api/core";
import { commit, createPr, push, repoInfo, type RepoInfo } from "../lib/gitops";
import { t, tErr } from "../lib/i18n";
import { DotSpinner, Icon } from "./Glyphs";
import "./commit.css";

export type CommitFile = {
  path: string;
  status: string;
  additions: number;
  deletions: number;
  /** Source path of a rename; committed together with the new path. */
  oldPath?: string | null;
};

type Props = {
  cwd: string;
  files: CommitFile[];
  /** Drafts the commit message from the current changes. */
  generateMessage?: () => Promise<string>;
  onClose: () => void;
  /** Called after a commit and after a push: the app should refresh git status. */
  onDone: () => void;
};

type Step = "form" | "committed" | "pr";
type Busy = "commit" | "push" | "pr" | null;

const STATUS_LETTER: Record<string, string> = {
  added: "A",
  modified: "M",
  deleted: "D",
  renamed: "R",
  untracked: "U",
  conflict: "C",
};

const STATUS_TITLE: Record<string, string> = {
  added: "Добавлен",
  modified: "Изменён",
  deleted: "Удалён",
  renamed: "Переименован",
  untracked: "Не отслеживается",
  conflict: "Конфликт",
};

/** Opens a link in the system browser; outside Tauri it falls back to a new window. */
function openLink(url: string): void {
  if (!isTauri()) {
    window.open(url, "_blank", "noopener,noreferrer");
    return;
  }
  openUrl(url).catch(() => window.open(url, "_blank", "noopener,noreferrer"));
}

export function CommitModal({ cwd, files, generateMessage, onClose, onDone }: Props): ReactElement {
  const uid = useId();
  const titleId = `${uid}-title`;
  const msgId = `${uid}-msg`;
  const prTitleId = `${uid}-pr-title`;
  const prBodyId = `${uid}-pr-body`;

  const [info, setInfo] = useState<RepoInfo | null>(null);
  const [infoError, setInfoError] = useState<string | null>(null);
  /** Paths of unchecked files. Files are checked by default. */
  const [excluded, setExcluded] = useState<string[]>([]);
  const [message, setMessage] = useState("");
  const [generating, setGenerating] = useState(false);
  const [genError, setGenError] = useState<string | null>(null);
  const [busy, setBusy] = useState<Busy>(null);
  const [error, setError] = useState<string | null>(null);
  const [step, setStep] = useState<Step>("form");
  const [hash, setHash] = useState("");
  const [committedMessage, setCommittedMessage] = useState("");
  const [pushed, setPushed] = useState(false);
  const [prTitle, setPrTitle] = useState("");
  const [prBody, setPrBody] = useState("");
  const [prUrl, setPrUrl] = useState<string | null>(null);
  const autoGenerated = useRef(false);

  const running = busy !== null || generating;
  const checked = files.filter((f) => !excluded.includes(f.path));
  // A rename is committed as a whole: the source path goes along with the new one.
  const checkedPaths = checked.flatMap((f) => (f.oldPath ? [f.path, f.oldPath] : [f.path]));
  const canCommit = !running && step === "form" && message.trim() !== "" && checkedPaths.length > 0;

  useEffect(() => {
    let cancelled = false;
    repoInfo(cwd)
      .then((next) => {
        if (!cancelled) setInfo(next);
      })
      .catch((e: unknown) => {
        if (!cancelled) setInfoError(tErr(e));
      });
    return () => {
      cancelled = true;
    };
  }, [cwd]);

  const runGenerate = async (auto: boolean) => {
    if (!generateMessage || generating) return;
    setGenerating(true);
    setGenError(null);
    try {
      const text = (await generateMessage()).trim();
      // The automatic draft never overwrites text the user has already typed.
      if (text) setMessage((prev) => (auto && prev.trim() ? prev : text));
    } catch (e) {
      setGenError(tErr(e));
    } finally {
      setGenerating(false);
    }
  };

  // Draft a message once on open, when the field is still empty.
  useEffect(() => {
    if (!generateMessage || autoGenerated.current) return;
    autoGenerated.current = true;
    void runGenerate(true);
  }, []);

  useEffect(() => {
    const onKey = (e: KeyboardEvent) => {
      if (e.key === "Escape" && !running) onClose();
    };
    window.addEventListener("keydown", onKey);
    return () => window.removeEventListener("keydown", onKey);
  }, [running, onClose]);

  const toggle = (path: string) => {
    setExcluded((prev) => (prev.includes(path) ? prev.filter((p) => p !== path) : [...prev, path]));
  };

  const doCommit = async () => {
    if (!canCommit) return;
    const text = message.trim();
    setBusy("commit");
    setError(null);
    try {
      const short = await commit(cwd, text, checkedPaths);
      setHash(short);
      setCommittedMessage(text);
      setStep("committed");
      onDone();
    } catch (e) {
      setError(tErr(e));
    } finally {
      setBusy(null);
    }
  };

  const doPush = async (thenPr: boolean) => {
    if (running) return;
    setBusy("push");
    setError(null);
    try {
      await push(cwd);
      setPushed(true);
      onDone();
      if (thenPr) openPrForm();
    } catch (e) {
      setError(tErr(e));
    } finally {
      setBusy(null);
    }
  };

  // The PR title is the commit summary line; the rest of the message becomes the body.
  const openPrForm = () => {
    const [summary = "", ...rest] = committedMessage.split("\n");
    setPrTitle(summary.trim());
    setPrBody(rest.join("\n").trim());
    setPrUrl(null);
    setError(null);
    setStep("pr");
  };

  const doPr = async () => {
    const title = prTitle.trim();
    if (!title || running) return;
    setBusy("pr");
    setError(null);
    try {
      const url = await createPr(cwd, title, prBody.trim(), info?.defaultBranch ?? null);
      setPrUrl(url);
    } catch (e) {
      setError(tErr(e));
    } finally {
      setBusy(null);
    }
  };

  const onMessageKey = (e: ReactKeyboardEvent<HTMLTextAreaElement>) => {
    if (e.key === "Enter" && (e.metaKey || e.ctrlKey)) {
      e.preventDefault();
      void doCommit();
    }
  };

  const branch = info?.branch ?? null;

  return (
    <div
      className="overlay"
      onClick={() => {
        if (!running) onClose();
      }}
    >
      <div
        className="card modal commit-modal"
        role="dialog"
        aria-modal="true"
        aria-labelledby={titleId}
        onClick={(e) => e.stopPropagation()}
      >
        <header className="commit-head">
          <h2 id={titleId}>{t("Коммит")}</h2>
          {branch && <span className="chip mono commit-branch">{branch}</span>}
          <button type="button" className="icon-btn" aria-label={t("Закрыть")} title={t("Закрыть (Esc)")} disabled={running} onClick={onClose}>
            <Icon name="close" size={16} />
          </button>
        </header>

        {infoError && (
          <div className="err-card commit-err" role="alert">
            {infoError}
          </div>
        )}

        {step === "form" && (
          <>
            <section className="commit-section">
              <span className="label">{t("Файлы для коммита")}</span>
              {files.length === 0 ? (
                <p className="commit-muted">{t("Нет изменений для коммита")}</p>
              ) : (
                <ul className="commit-files">
                  {files.map((f) => {
                    const on = !excluded.includes(f.path);
                    return (
                      <li key={f.path}>
                        <label className="commit-file">
                          <input type="checkbox" checked={on} disabled={running} onChange={() => toggle(f.path)} />
                          <span className={`commit-badge s-${f.status}`} title={t(STATUS_TITLE[f.status] ?? f.status)}>
                            {STATUS_LETTER[f.status] ?? "?"}
                          </span>
                          <span className="commit-file-path" title={f.path}>
                            {f.path}
                          </span>
                          <span className="commit-nums">
                            <span className="commit-add">+{f.additions}</span>
                            <span className="commit-del">−{f.deletions}</span>
                          </span>
                        </label>
                      </li>
                    );
                  })}
                </ul>
              )}
            </section>

            <section className="commit-section">
              <div className="commit-msg-head">
                <label className="label" htmlFor={msgId}>
                  {t("Сообщение коммита")}
                </label>
                {generateMessage && (
                  <button type="button" className="btn commit-gen" disabled={running} onClick={() => void runGenerate(false)}>
                    {generating && <DotSpinner size={12} />}
                    {t("Сгенерировать")}
                  </button>
                )}
              </div>
              <textarea
                id={msgId}
                className="commit-msg"
                rows={5}
                value={message}
                disabled={running}
                onChange={(e) => setMessage(e.target.value)}
                onKeyDown={onMessageKey}
              />
              {genError && (
                <div className="commit-inline-err" role="alert">
                  {genError}
                </div>
              )}
            </section>

            {error && (
              <div className="err-card commit-err" role="alert">
                {error}
              </div>
            )}

            <div className="commit-actions">
              <button type="button" className="btn" disabled={running} onClick={onClose}>
                {t("Отмена")}
              </button>
              <button type="button" className="btn primary" disabled={!canCommit} onClick={() => void doCommit()}>
                {busy === "commit" && <DotSpinner size={12} />}
                {t("Закоммитить")}
              </button>
            </div>
          </>
        )}

        {step === "committed" && (
          <>
            <section className="commit-section commit-done">
              <p className="commit-result">{t("Коммит {hash} создан", { hash })}</p>
              {pushed && <p className="commit-muted">{t("Запушено")}</p>}
            </section>

            {error && (
              <div className="err-card commit-err" role="alert">
                {error}
              </div>
            )}

            <div className="commit-actions">
              {!pushed && (
                <button type="button" className="btn" disabled={running} onClick={() => void doPush(false)}>
                  {busy === "push" && <DotSpinner size={12} />}
                  {t("Запушить")}
                </button>
              )}
              {!pushed && info?.hasGh && (
                <button type="button" className="btn" disabled={running} onClick={() => void doPush(true)}>
                  {t("Запушить и создать PR")}
                </button>
              )}
              {pushed && info?.hasGh && (
                <button type="button" className="btn" disabled={running} onClick={openPrForm}>
                  {t("Создать PR")}
                </button>
              )}
              <button type="button" className="btn primary" disabled={running} onClick={onClose}>
                {t("Готово")}
              </button>
            </div>
          </>
        )}

        {step === "pr" && (
          <>
            <section className="commit-section">
              <label className="label" htmlFor={prTitleId}>
                {t("Заголовок PR")}
              </label>
              <input
                id={prTitleId}
                className="commit-input"
                value={prTitle}
                disabled={busy === "pr" || prUrl !== null}
                onChange={(e) => setPrTitle(e.target.value)}
              />
            </section>

            <section className="commit-section">
              <label className="label" htmlFor={prBodyId}>
                {t("Описание PR")}
              </label>
              <textarea
                id={prBodyId}
                className="commit-msg"
                rows={5}
                value={prBody}
                disabled={busy === "pr" || prUrl !== null}
                onChange={(e) => setPrBody(e.target.value)}
              />
              {info?.defaultBranch && <p className="commit-muted mono">{t("Базовая ветка: {base}", { base: info.defaultBranch })}</p>}
            </section>

            {prUrl && (
              <section className="commit-section">
                <span className="label">{t("PR создан")}</span>
                <a
                  className="commit-pr-link"
                  href={prUrl}
                  target="_blank"
                  rel="noopener noreferrer"
                  onClick={(e) => {
                    e.preventDefault();
                    openLink(prUrl);
                  }}
                >
                  {prUrl}
                </a>
              </section>
            )}

            {error && (
              <div className="err-card commit-err" role="alert">
                {error}
              </div>
            )}

            <div className="commit-actions">
              {prUrl === null ? (
                <>
                  <button type="button" className="btn" disabled={running} onClick={onClose}>
                    {t("Отмена")}
                  </button>
                  <button type="button" className="btn primary" disabled={!prTitle.trim() || running} onClick={() => void doPr()}>
                    {busy === "pr" && <DotSpinner size={12} />}
                    {t("Создать PR")}
                  </button>
                </>
              ) : (
                <button type="button" className="btn primary" onClick={onClose}>
                  {t("Готово")}
                </button>
              )}
            </div>
          </>
        )}
      </div>
    </div>
  );
}
